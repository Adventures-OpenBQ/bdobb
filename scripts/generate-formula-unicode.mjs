// Opt-in reproduction only: node scripts/generate-formula-unicode.mjs
// This is never run by a build or test. Changing the repertoire requires review.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
if (process.version !== 'v26.10.0' || process.versions.unicode !== '17.0') {
  throw new Error('Reproduction requires baseline Node v26.10.0 with Unicode 17.0');
}
const filename = path.join(path.dirname(fileURLToPath(import.meta.url)), '../crates/pivot-core/src/formulas/syntax.rs');
let output = '\n// Unicode 17.0 general-category ranges captured from baseline Node v26.10.0.\n';
output += '// Reproduce explicitly with scripts/generate-formula-unicode.mjs; never regenerated by builds/tests.\n';
output += '// Names use exactly \\p{L} initially and \\p{L} / \\p{N} thereafter; bracket names are unrestricted.\n';
for (const [name, pattern] of [['LETTERS', /^\p{L}$/u], ['NUMBERS', /^\p{N}$/u]]) {
  const ranges = [];
  let begin = -1;
  let end = -1;
  for (let codepoint = 0; codepoint <= 0x10ffff; codepoint++) {
    if (pattern.test(String.fromCodePoint(codepoint))) {
      if (begin < 0) begin = codepoint;
      end = codepoint;
    } else if (begin >= 0) {
      ranges.push([begin, end]);
      begin = -1;
    }
  }
  if (begin >= 0) ranges.push([begin, end]);
  output += `const ${name}: &[(u32, u32)] = &[\n`;
  output += ranges.map(([start, finish]) => `    (0x${start.toString(16)}, 0x${finish.toString(16)}),`).join('\n');
  output += '\n];\n';
}
const source = fs.readFileSync(filename, 'utf8');
fs.writeFileSync(filename, source.replace(/\n\/\/ Unicode [\s\S]*$/, output));
