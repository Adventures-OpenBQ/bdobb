import { test } from 'node:test';
import { execFileSync } from 'node:child_process';
import assert from 'node:assert/strict';
import { cp, mkdtemp, readFile, rm, appendFile, writeFile, symlink } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

// Removing the Vite hook or accepting an altered artifact makes these fail.
test('the pinned artifact verifier refuses missing, stale source and altered generated bytes', async t => {
 const { ensurePivotWasm } = await import('./build-pivot-wasm.mjs');
 assert.equal(typeof ensurePivotWasm, 'function', 'All Vite entry points need an artifact verifier');
 const root = await mkdtemp(join(tmpdir(), 'pivot-package-'));
 t.after(() => rm(root, { recursive: true, force: true }));
 for (const name of ['crates/pivot-core', 'crates/pivot-wire', 'crates/pivot-wasm', 'scripts', 'src/lib/tableExecution/rust/generated']) {
  await cp(resolve(name), join(root, name), { recursive: true, filter: path => !path.includes('/target') });
 }
 await ensurePivotWasm({ root, verifyOnly: true });
 const source = join(root, 'crates/pivot-core/src/lib.rs');
 await appendFile(source, '\n// stale source\n');
 await assert.rejects(ensurePivotWasm({ root, verifyOnly: true }), /stale/);
 await cp(resolve('crates/pivot-core/src/lib.rs'), source);
 const sharedSource = join(root, 'crates/pivot-wire/src/lib.rs');
 await appendFile(sharedSource, '\n// stale shared wire codec\n');
 await assert.rejects(ensurePivotWasm({ root, verifyOnly: true }), /stale/);
 await cp(resolve('crates/pivot-wire/src/lib.rs'), sharedSource);
 const glue = join(root, 'src/lib/tableExecution/rust/generated/pivot_wasm.js');
 await appendFile(glue, '\n// tampered glue\n');
 await assert.rejects(ensurePivotWasm({ root, verifyOnly: true }), /stale/);
 await cp(resolve('src/lib/tableExecution/rust/generated/pivot_wasm.js'), glue);
 const wasm = join(root, 'src/lib/tableExecution/rust/generated/pivot_wasm_bg.wasm');
 await appendFile(wasm, Buffer.from([0]));
 await assert.rejects(ensurePivotWasm({ root, verifyOnly: true }), /stale/);
 await rm(wasm);
 await assert.rejects(ensurePivotWasm({ root, verifyOnly: true }), /missing/);
 await cp(resolve('vite.config.ts'),join(root,'vite.config.ts'));
 await cp(resolve('package.json'),join(root,'package.json'));
 await symlink(resolve('node_modules'),join(root,'node_modules'),'dir');
 await writeFile(join(root,'index.html'),'<html><body>build entry probe</body></html>');
 const options={cwd:root,env:{...process.env,PIVOT_WASM_VERIFY_ONLY:'1'},encoding:'utf8'};
 const refuses=(command,args)=>assert.throws(()=>execFileSync(command,args,options),error=>/Pivot Wasm artifact is missing/.test(error.stderr));
 const vite=resolve('node_modules/vite/bin/vite.js');
 refuses(process.execPath,[vite,'build']);
 refuses(process.execPath,[vite,'--mode','browser']);
 refuses(process.execPath,[join(root,'scripts/build-web.mjs')]);
 await cp(resolve('src/lib/tableExecution/rust/generated/pivot_wasm_bg.wasm'),wasm);
 await appendFile(source,'\n// Vite must refuse stale source\n');
 assert.throws(()=>execFileSync(process.execPath,[vite,'build'],options),error=>/Pivot Wasm artifact is stale/.test(error.stderr));
});
