// Orchestration fault injection uses real copied Wasm bytes; it is not compiler parity evidence.
test('concurrent missing/stale builds share one promise and a failed owner permits a clean retry', async t => {
 const { ensurePivotWasm }=await import('./build-pivot-wasm.mjs');
 const root=await mkdtemp(join(tmpdir(),'pivot-concurrent-'));
 t.after(()=>rm(root,{recursive:true,force:true}));
 for(const name of ['crates/pivot-core','crates/pivot-wire','crates/pivot-wasm','scripts','src/lib/tableExecution/rust/generated','package.json'])
  await cp(resolve(name),join(root,name),{recursive:true,filter:path=>!path.includes('/target')});
 const {mkdir,chmod}=await import('node:fs/promises');
 const bin=join(root,'fake-tools');await mkdir(bin);await mkdir(join(root,'.pivot-tools/bin'),{recursive:true});
 const log=join(root,'build-calls.jsonl'),failure=join(root,'fail-cargo');
 const mock=`#!${process.execPath}\nimport {appendFileSync,existsSync} from 'node:fs';\nimport {basename} from 'node:path';\nconst tool=basename(process.argv[1]);\nif(process.argv.includes('--version')){console.log(tool==='rustc'?'rustc 1.98.1 (mock)':'wasm-bindgen 0.2.128');}else{appendFileSync(${JSON.stringify(log)},tool+'\\n');await new Promise(resolve=>setTimeout(resolve,100));if(tool==='cargo'&&existsSync(${JSON.stringify(failure)}))process.exit(1);}\n`;
 for(const name of ['cargo','rustc']){await writeFile(join(bin,name),mock);await chmod(join(bin,name),0o755);}
 const bindgen=join(root,'.pivot-tools/bin/wasm-bindgen');await writeFile(bindgen,mock);await chmod(bindgen,0o755);
 const oldPath=process.env.PATH,oldBindgen=process.env.PIVOT_WASM_BINDGEN;
 process.env.PATH=`${bin}:${oldPath}`;process.env.PIVOT_WASM_BINDGEN=bindgen;
 t.after(()=>{process.env.PATH=oldPath;if(oldBindgen===undefined)delete process.env.PIVOT_WASM_BINDGEN;else process.env.PIVOT_WASM_BINDGEN=oldBindgen;});
 const calls=async()=>{try{return (await readFile(log,'utf8')).trim().split('\n');}catch(error){if(error.code==='ENOENT')return [];throw error;}};
 const concurrent=()=>Promise.all([ensurePivotWasm({root,verifyOnly:false}),ensurePivotWasm({root,verifyOnly:false}),ensurePivotWasm({root,verifyOnly:false})]);
 await rm(join(root,'src/lib/tableExecution/rust/generated/build-stamp.json'),{force:true});
 await concurrent();assert.deepEqual(await calls(),['cargo','wasm-bindgen'],'missing artifact must build once');
 await writeFile(log,'');await appendFile(join(root,'crates/pivot-core/src/lib.rs'),'\n// stale source\n');
 await concurrent();assert.deepEqual(await calls(),['cargo','wasm-bindgen'],'stale artifact must build once');
 await writeFile(log,'');await writeFile(failure,'fail');await rm(join(root,'src/lib/tableExecution/rust/generated/build-stamp.json'));
 const rejected=await Promise.allSettled([ensurePivotWasm({root,verifyOnly:false}),ensurePivotWasm({root,verifyOnly:false}),ensurePivotWasm({root,verifyOnly:false})]);
 assert.equal(rejected.filter(value=>value.status==='rejected').length,3);assert.deepEqual(await calls(),['cargo'],'failed shared build must have one owner');
 await rm(failure);await concurrent();assert.deepEqual(await calls(),['cargo','cargo','wasm-bindgen'],'all new callers must share one clean retry after failure');
 await appendFile(join(root,'src/lib/tableExecution/rust/generated/pivot_wasm_bg.wasm'),Buffer.from([0]));
 const invalid=await Promise.allSettled([ensurePivotWasm({root,verifyOnly:false}),ensurePivotWasm({root,verifyOnly:false}),ensurePivotWasm({root,verifyOnly:false})]);
 assert.equal(invalid.filter(value=>value.status==='rejected').length,3,'real emitted-module smoke must run even from a Node test runner');
});
