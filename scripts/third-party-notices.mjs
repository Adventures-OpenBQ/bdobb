/**
 * Writes THIRD_PARTY_NOTICES.md from what actually ships: the production
 * dependency closure of package.json (as installed from pnpm-lock.yaml) and
 * the normal-dependency closures of the Tauri and portable Pivot crates (from Cargo.lock).
 *
 *   node scripts/third-party-notices.mjs           rewrite the file
 *   node scripts/third-party-notices.mjs --check   fail if it is out of date
 *
 * Each package lists its name, version, declared license and the copyright
 * lines of its own license file. License texts are printed once per distinct
 * text (copyright lines removed before comparing), with the packages that use
 * it, so a few hundred MIT packages do not repeat the MIT text a few hundred
 * times. Offline: both sources are read from the local install and registry.
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { shippedCrates } from "./cargo-closure.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "THIRD_PARTY_NOTICES.md");
const LICENSE_FILE = /^(licen[cs]e|copying|notice)([-._].*)?$/i;
// An owner line ("Copyright (c) 2016 Jane Doe", "(c) 2020 Mapbox"), not license
// boilerplate that merely mentions copyright ("the above copyright notice ...").
const COPYRIGHT_LINE = /^\s*(copyright\b(?!\s+(notice|notices|owner|holders?|license|and|statement|law|protection)\b)|\(c\)\s+(?!you\b)|©)/i;

function licenseTexts(dir) {
  if (!dir || !existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((name) => LICENSE_FILE.test(name))
    .sort()
    .map((name) => readFileSync(join(dir, name), "utf8").replace(/\r\n?/g, "\n").trim())
    .filter(Boolean);
}

const PLATFORM_BINARY = /-(darwin|linux|win32|android|freebsd)-(arm64|x64|ia32|arm)(-(gnu|musl|msvc|gnueabihf))?$/;

function npmPackages() {
  const json = JSON.parse(
    execFileSync("pnpm", ["licenses", "list", "--prod", "--json"], { cwd: ROOT, encoding: "utf8", maxBuffer: 1 << 28 }),
  );
  const out = [];
  for (const group of Object.values(json)) {
    for (const p of group) {
      // A per-platform native binary (pdfjs-dist's optional @napi-rs/canvas-*)
      // is whichever one this machine installed, so listing it would make the
      // file differ between a Mac and the Linux CI runner. None of them ships.
      if (PLATFORM_BINARY.test(p.name)) continue;
      p.versions.forEach((version, i) =>
        out.push({ name: p.name, version, license: ({"@plotly/mapbox-gl@1.13.4": "BSD-3-Clause", "mapbox-gl@1.13.3": "BSD-3-Clause", "stack-trace@0.0.9": "MIT"})[`${p.name}@${version}`] ?? p.license, texts: licenseTexts(p.paths[i] ?? p.paths[0]) }),
      );
    }
  }
  return out;
}

function cratesFor(manifest) {
  return shippedCrates(join(ROOT, manifest, "Cargo.toml"), ["--offline"])
    .map((p) => ({
      name: p.name,
      version: p.version,
      license: p.license ?? (p.license_file ? `see ${p.license_file}` : "UNKNOWN"),
      texts: licenseTexts(dirname(p.manifest_path)),
    }));
}

function crates() {
  const packages = new Map();
  for (const manifest of ["src-tauri", "crates/pivot-core", "crates/pivot-wasm"]) {
    for (const pkg of cratesFor(manifest)) packages.set(`${pkg.name}@${pkg.version}`, pkg);
  }
  return [...packages.values()];
}

const byName = (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version, undefined, { numeric: true });
const cell = (s) => s.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();

function render() {
  const sections = [
    ["JavaScript packages", npmPackages().sort(byName)],
    ["Rust crates", crates().sort(byName)],
  ];
  const texts = new Map(); // normalised body -> { body, license, users }
  const lines = [
    "# Third-party notices",
    "",
    "BDOBB is Copyright 2026 SecretoftheUniverse.com LLC and licensed under AGPL-3.0-only (see `LICENSE`, `LICENSING.md` and `NOTICE`).",
    "It ships the third-party components below, each under its own license. This file is generated by `node scripts/third-party-notices.mjs`",
    "from `pnpm-lock.yaml` (production dependencies) and `src-tauri/Cargo.lock`, `crates/pivot-core/Cargo.lock` and `crates/pivot-wasm/Cargo.lock` (normal dependencies);",
    "`node scripts/third-party-notices.mjs --check` fails when it is out of date.",
    "",
    "Art and fonts: the application icons (`src-tauri/icons`), the favicons and web-app icons (`public/`) and `src/assets/branding`",
    "are original BDOBB art. Interface icons drawn from third-party artwork are credited under Icons below. The interface uses",
    "the operating system's fonts for its UI; the PDF viewer separately bundles PDFium/Foxit fonts (BSD-3-Clause) and Liberation fonts (OFL-1.1). OpenBB and the OpenBB \"BB\" mark are trademarks of OpenBB Inc.,",
    "used only to identify OpenBB connections.",
    "Charts drawn with TradingView Lightweight Charts carry the visible credit \"Rendered by TradingView\".",
    "",
    "A package marked \"(no license file shipped)\" publishes only its license identifier; the standard text of that license",
    "appears below under License texts, printed for another package under the same license.",
    "",
  ];
  // PDF fonts are emitted by vite.config.ts and carry separate licenses.
  lines.push("## PDF viewer fonts", "", "Vite emits the pdfjs-dist/standard_fonts directory, including its license files.", "These fonts retain their own terms and are not relicensed under AGPL.", "");
  for (const name of ["LICENSE_FOXIT", "LICENSE_LIBERATION"]) {
    const text = readFileSync(join(ROOT, "LICENSES", "pdfjs-standard-fonts", name), "utf8").trimEnd();
    lines.push(`### ${name}`, "", "````text", text, "````", "");
  }
  // Icon credits travel with the icons: src/assets/icons/LICENSE.md, demoted one heading level.
  const icons = join(ROOT, "src", "assets", "icons", "LICENSE.md");
  if (existsSync(icons)) {
    lines.push(readFileSync(icons, "utf8").replace(/^(#+) /gm, "#$1 ").trim(), "");
  }
  for (const [title, pkgs] of sections) {
    lines.push(`## ${title} (${pkgs.length})`, "", "| Package | Version | License | Copyright |", "|---|---|---|---|");
    for (const p of pkgs) {
      const owners = new Set();
      for (const text of p.texts) {
        const body = text.split("\n").filter((l) => !COPYRIGHT_LINE.test(l)).join("\n").replace(/[ \t]+/g, " ").trim();
        text.split("\n").filter((l) => COPYRIGHT_LINE.test(l)).forEach((l) => owners.add(l.trim()));
        const key = createHash("sha256").update(body.replace(/\s+/g, " ")).digest("hex");
        if (!texts.has(key)) texts.set(key, { body, license: p.license, users: [] });
        texts.get(key).users.push(`${p.name}@${p.version}`);
      }
      const copyright = owners.size ? [...owners].join("; ") : p.texts.length ? "(none stated in its license file)" : "(no license file shipped)";
      lines.push(`| ${cell(p.name)} | ${cell(p.version)} | ${cell(p.license)} | ${cell(copyright)} |`);
    }
    lines.push("");
  }
  lines.push("## License texts", "");
  let n = 0;
  for (const { body, license, users } of texts.values()) {
    n += 1;
    lines.push(`### Text ${n} (${license})`, "", `Used by: ${[...new Set(users)].join(", ")}`, "", "````text", body, "````", "");
  }
  return lines.join("\n");
}

const next = render();
if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== next) {
    console.error("third-party-notices: FAILED — THIRD_PARTY_NOTICES.md is out of date; run node scripts/third-party-notices.mjs");
    process.exit(1);
  }
  console.log("third-party-notices: up to date");
} else {
  writeFileSync(OUT, next);
  console.log(`third-party-notices: wrote ${OUT.slice(ROOT.length + 1)}`);
}
