// Run with the authoritative B1 schema path; committed schema permits offline regeneration.
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const path=process.argv[2] ?? 'src/lib/temporal/temporal-v1.schema.json';
const bytes=readFileSync(path);const schema=JSON.parse(bytes);
if(schema.$id!=='urn:temporaldb:contracts:v1')throw Error('Unsupported contract schema');
const type=s=>{
 if(s.$ref)return s.$ref.split('/').at(-1);
 if(s.const!==undefined)return JSON.stringify(s.const);
 if(s.enum)return s.enum.map(x=>JSON.stringify(x)).join(' | ');
 if(s.anyOf)return s.anyOf.map(type).join(' | ');
 if(s.type==='array')return `(${type(s.items)})[]`;
 if(s.type==='object'){
  if(!s.properties)return `Record<string, ${s.additionalProperties===true?'unknown':type(s.additionalProperties??{})}>`;
  return '{ '+Object.entries(s.properties).map(([k,v])=>`${JSON.stringify(k)}${s.required?.includes(k)?'':'?'}: ${type(v)}`).join('; ')+' }';
 }
 return ({string:'string',integer:'number',number:'number',boolean:'boolean',null:'null'})[s.type]??'unknown';
};
const header='// Copyright 2026 SecretoftheUniverse.com LLC. Licensed under the GNU Affero General Public License, version 3 only.\n// SPDX-License-Identifier: AGPL-3.0-only\n';
writeFileSync('src/lib/temporal/temporal-v1.schema.json',bytes);
writeFileSync('src/lib/temporal/generated.ts',header+`// Generated by scripts/generate-temporal-contracts.mjs; B1 SHA256 ${createHash('sha256').update(bytes).digest('hex')}\n`+Object.entries(schema.$defs).map(([name,s])=>`export type ${name} = ${type(s)};`).join('\n')+'\nexport type ContractTypes = { '+Object.keys(schema.$defs).map(name=>`${name}: ${name}`).join('; ')+' };\nexport const contractSchema = '+JSON.stringify(schema)+';\n');
